    // In bảng phân bố theo danh mục
    const categories = await Product.aggregate([
      { $group: { _id: '$category', count: { $sum: 1 }, avgPrice: { $avg: '$price' } } },
    ]);
    console.table(
      categories.map((c) => ({
        'Danh mục': c._id,
        'Số lượng': c.count,
        'Giá trung bình (VND)': Math.round(c.avgPrice).toLocaleString('vi-VN'),
      }))
    );

    await mongoose.connection.close();
    process.exit(0);
